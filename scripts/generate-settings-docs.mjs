import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import messages from "../messages/en.json" with { type: "json" };
import {
  generateSettingsDocs,
  generateSettingsMessages,
  mergeGeneratedSettingsMessages,
  serializeMessages,
  SETTINGS_PREVIEW_INPUT,
} from "../lib/settingsDocsGenerator.mjs";
import { formatMessage } from "../lib/messages.mjs";
import { toJavaScriptLiteral } from "../lib/optionsSerialization.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const outputPath = path.resolve(__dirname, "../app/generated/settings-docs.ts");
const messagesPath = path.resolve(__dirname, "../messages/en.json");
const checkMode = process.argv.includes("--check");

function createModuleContent() {
  const docs = generateSettingsDocs();
  const inputLiteral = toJavaScriptLiteral(SETTINGS_PREVIEW_INPUT);

  return `/* eslint-disable */\n/* AUTO-GENERATED FILE. DO NOT EDIT. */\n/* Generated by scripts/generate-settings-docs.mjs */\n\nexport type GeneratedTypeDefinition = {\n  name: string;\n  signature: string;\n};\n\nexport type GeneratedSettingDoc = {\n  key: string;\n  anchor: string;\n  typeSignature: string;\n  typeDefinitions: GeneratedTypeDefinition[];\n  exampleSettings: string;\n  preview: string;\n};\n\nexport const SETTINGS_PREVIEW_INPUT = ${inputLiteral};\n\nexport const SETTINGS_PREVIEW_INPUT_CODE = ${JSON.stringify(inputLiteral)};\n\nexport const SETTINGS_DOCS: GeneratedSettingDoc[] = ${JSON.stringify(docs, null, 2)};\n`;
}

function createMessagesContent() {
  return serializeMessages(
    mergeGeneratedSettingsMessages(messages, generateSettingsMessages()),
  );
}

const generatedContent = createModuleContent();
const generatedMessagesContent = createMessagesContent();

if (checkMode) {
  if (!fs.existsSync(outputPath)) {
    console.error(
      formatMessage(messages.generator.errors.missingGeneratedDocs, {
        path: outputPath,
      }),
    );
    process.exit(1);
  }

  const currentContent = fs.readFileSync(outputPath, "utf8");

  if (currentContent !== generatedContent) {
    console.error(messages.generator.errors.staleGeneratedDocs);
    process.exit(1);
  }

  if (!fs.existsSync(messagesPath)) {
    console.error(
      formatMessage(messages.generator.errors.missingMessages, {
        path: messagesPath,
      }),
    );
    process.exit(1);
  }

  const currentMessagesContent = fs.readFileSync(messagesPath, "utf8");

  if (currentMessagesContent !== generatedMessagesContent) {
    console.error(messages.generator.errors.staleMessages);
    process.exit(1);
  }

  console.log(messages.generator.logs.docsCurrent);
  process.exit(0);
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, generatedContent, "utf8");
fs.writeFileSync(messagesPath, generatedMessagesContent, "utf8");
console.log(
  formatMessage(messages.generator.logs.docsWritten, {
    path: outputPath,
  }),
);
console.log(
  formatMessage(messages.generator.logs.messagesWritten, {
    path: messagesPath,
  }),
);
