import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import messages from "../messages/en.json" with { type: "json" };
import { generateApiDocs } from "../lib/settingsDocsGenerator.mjs";
import { DOCUMENTATION_VERSIONS } from "../lib/documentationVersions.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const outputPath = path.resolve(__dirname, "../app/generated/api-docs.ts");
const checkMode = process.argv.includes("--check");

function createModuleContent() {
  const docsByVersion = Object.fromEntries(
    DOCUMENTATION_VERSIONS.map(({ id }) => [id, generateApiDocs({ version: id })]),
  );

  return `/* eslint-disable */
/* AUTO-GENERATED FILE. DO NOT EDIT. */
/* Generated by scripts/generate-settings-docs.mjs */

export type GeneratedOptionDoc = {
  key: string;
  anchor: string;
  typeSignature: string;
  description: string;
  required: boolean;
  exampleIds: string[];
};

export type GeneratedTypeReference = {
  name: string;
  description: string;
  signature: string;
  options: GeneratedOptionDoc[];
};

export type GeneratedExampleDoc = {
  id: string;
  surface: string;
  code: string;
  output: string;
  covers: string[];
};

export type GeneratedExportDoc = {
  name: string;
  description: string;
  signature: string;
};

export type GeneratedApiSurface = {
  id: string;
  signature: string;
  groups: string[];
  optionGroups: GeneratedTypeReference[];
  typeReferences: GeneratedTypeReference[];
  examples: GeneratedExampleDoc[];
  exports: GeneratedExportDoc[];
};

export const API_DOCS_BY_VERSION: Record<string, GeneratedApiSurface[]> = ${JSON.stringify(
    docsByVersion,
    null,
    2,
  )};
`;
}

const generatedContent = createModuleContent();

if (checkMode) {
  if (!fs.existsSync(outputPath)) {
    console.error(
      messages.generator.errors.missingGeneratedDocs.replace(
        "{path}",
        outputPath,
      ),
    );
    process.exit(1);
  }

  if (fs.readFileSync(outputPath, "utf8") !== generatedContent) {
    console.error(messages.generator.errors.staleGeneratedDocs);
    process.exit(1);
  }

  console.log(messages.generator.logs.docsCurrent);
  process.exit(0);
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, generatedContent, "utf8");
console.log(messages.generator.logs.docsWritten.replace("{path}", outputPath));
